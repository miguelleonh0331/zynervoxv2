CREATE TABLE IF NOT EXISTS zynervox_bot_tts_providers (
 provider_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 endpoint VARCHAR(512) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_bot_tts_endpoint (endpoint)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
