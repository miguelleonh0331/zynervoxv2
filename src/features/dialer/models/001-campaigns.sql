CREATE TABLE IF NOT EXISTS v2_dialer_campaigns (
  campaign_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(120) NOT NULL,
  active TINYINT(1) NOT NULL DEFAULT 1,
  carrier_id VARCHAR(60) NOT NULL,
  dial_prefix VARCHAR(20) NOT NULL DEFAULT '',
  caller_id_number VARCHAR(20) NOT NULL DEFAULT '',
  dial_method ENUM('MANUAL','RATIO','ADAPTIVE') NOT NULL DEFAULT 'MANUAL',
  dial_level DECIMAL(5,2) NOT NULL DEFAULT 1.00,
  level_count_mode ENUM('WAITING','NON_PAUSED','LOGGED_IN') NOT NULL DEFAULT 'WAITING',
  adaptive_target_abandon_pct DECIMAL(5,2) NOT NULL DEFAULT 3.00,
  adaptive_max_level DECIMAL(5,2) NOT NULL DEFAULT 3.00,
  adaptive_min_level DECIMAL(5,2) NOT NULL DEFAULT 1.00,
  adaptive_step DECIMAL(5,2) NOT NULL DEFAULT 0.10,
  adaptive_min_sample INT UNSIGNED NOT NULL DEFAULT 30,
  max_concurrent_calls INT UNSIGNED NOT NULL DEFAULT 5,
  dial_timeout_seconds INT UNSIGNED NOT NULL DEFAULT 25,
  drop_call_seconds INT UNSIGNED NOT NULL DEFAULT 8,
  drop_action ENUM('HANGUP','MESSAGE') NOT NULL DEFAULT 'HANGUP',
  amd_enabled TINYINT(1) NOT NULL DEFAULT 1,
  amd_action_machine ENUM('HANGUP','MESSAGE') NOT NULL DEFAULT 'HANGUP',
  local_call_time_start TIME NOT NULL DEFAULT '08:00:00',
  local_call_time_end TIME NOT NULL DEFAULT '19:00:00',
  max_attempts_per_lead INT UNSIGNED NOT NULL DEFAULT 6,
  wrapup_seconds INT UNSIGNED NOT NULL DEFAULT 15,
  lead_order ENUM('RANK_ASC','OLDEST_FIRST','RANDOM','LAST_CALL_ASC') NOT NULL DEFAULT 'OLDEST_FIRST',
  queue_name VARCHAR(40) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (campaign_id),
  UNIQUE KEY uq_dialer_campaigns_queue (queue_name),
  KEY idx_dialer_campaigns_carrier (carrier_id),
  CONSTRAINT fk_dialer_campaigns_carrier FOREIGN KEY (carrier_id)
    REFERENCES v2_carriers (carrier_id) ON DELETE RESTRICT,
  CHECK (active IN (0,1)), CHECK (amd_enabled IN (0,1)),
  CHECK (local_call_time_start >= '00:00:00' AND local_call_time_start < '24:00:00'),
  CHECK (local_call_time_end >= '00:00:00' AND local_call_time_end < '24:00:00')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
